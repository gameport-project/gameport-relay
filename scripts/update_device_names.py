#!/usr/bin/env python3
"""Rebuilds device_names.generated.js from the public list of Google Play's supported devices (the android-device-list project, MIT).

Maps Build.MODEL to a readable name, and Build.DEVICE to the same when the model is not known. The headsets that list lacks are in device_names.js, by hand.
Usage: python3 scripts/update_device_names.py [path to a devices.json]  (downloads it when no path is given)
"""
import json
import sys
import urllib.request
from pathlib import Path

SOURCE = "https://raw.githubusercontent.com/pbakondy/android-device-list/master/devices.json"
OUT = Path(__file__).resolve().parent.parent / "device_names.generated.js"
PLAIN = __import__("re").compile(r"^[0-9A-Za-z][0-9A-Za-z ._+\-/()]{0,39}$")


def main() -> None:
    if len(sys.argv) > 1:
        devices = json.loads(Path(sys.argv[1]).read_text())
    else:
        with urllib.request.urlopen(SOURCE, timeout=60) as response:
            devices = json.load(response)
    models: dict[str, str] = {}
    codenames: dict[str, str] = {}
    for entry in devices:
        brand, name, device, model = (str(entry.get(key, "")).strip() for key in ("brand", "name", "device", "model"))
        if not name:
            continue
        label = name if name.lower().startswith(brand.lower()) or not brand else f"{brand} {name}"
        if PLAIN.match(model) and label != model:
            models.setdefault(model, label)
        if PLAIN.match(device) and label != device and device != model:
            codenames.setdefault(device, label)
    body = json.dumps({"models": dict(sorted(models.items())), "codenames": dict(sorted(codenames.items()))}, ensure_ascii=False, separators=(",", ":"))
    OUT.write_text(f"// Generated by scripts/update_device_names.py from Google Play's list of supported devices. Do not edit by hand: see device_names.js for that.\nexport default {body};\n")
    print(f"{len(models)} models, {len(codenames)} codenames, {OUT.stat().st_size // 1024} KB")


main()
